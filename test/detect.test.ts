describe('detect: the score formula', () => {
  it("is P × T: 'a,b\\n1,2\\n3\\n' under ',' scores 1/6", () => {
    // N = 3, K = 2: P = (1/2) × ((2/3) × (1/2) + (1/3) × 0) = 1/6; every cell is clean: T = 1.
    const found = detect('a,b\n1,2\n3\n');
    expect(found.delimiter).toBe(',');
    expect(found.columns).toBe(2);
    expect(Math.abs(found.score - 1 / 6)).toBeLessThan(1e-12);
    // Every other delimiter gives one field per record: P = 0.
    expect(found.candidates.slice(1).map((c) => c.score)).toStrictEqual([0, 0, 0, 0]);
  });

  it('counts a quoted cell that holds a candidate delimiter as not clean', () => {
    // P = 1/2 (three records of two fields); 4 of 6 cells are clean.
    const found = detect('name,city\n"Doe, J",Paris\n"Roe, R",Rome\n');
    expect(Math.abs(found.score - 1 / 3)).toBeLessThan(1e-12);
  });

  it('floors T at 1e-10', () => {
    // Under ',' with '"': one record of two fields, both holding a quote: P = 1/2, T = 0.
    const found = detect('x"y,z"w\n');
    expect(found.delimiter).toBe(',');
    expect(Math.abs(found.score - 0.5e-10)).toBeLessThan(1e-20);
  });

  it('takes the larger field count when two are equally frequent', () => {
    expect(detect('a,b\n1\n').columns).toBe(2);
  });

  it('resolves ties by delimiter order, then \'"\' before "\'", then doubled before "\\"', () => {
    // ',' and '|' both read two records of two fields with 2 of 4 cells clean: 1/4 each.
    const byDelimiter = detect('a,b|c\nd,e|f\n');
    expect(byDelimiter.candidates.map((c) => [c.delimiter, c.score])).toStrictEqual([
      [',', 0.25],
      ['|', 0.25],
      ['\t', 0],
      [';', 0],
      ['\x1e', 0],
    ]);
    // Quotes inside a field are data for all four readings, so they tie at 1/2 × 2/4.
    const byQuote = detect("x,y\nit's,a\\\"b\\'c\n");
    expect(
      byQuote.candidates.map((c) => [c.delimiter, c.quoteChar, c.escapeChar, c.score]),
    ).toStrictEqual([
      [',', '"', '"', 0.25],
      [',', '"', '\\', 0.25],
      [',', "'", "'", 0.25],
      [',', "'", '\\', 0.25],
      ['\t', '"', '"', 0],
    ]);
  });

  it('scores the "\'" candidates only when the sample holds one, and "\\" only before that quote', () => {
    expect(new Set(detect('a,b\n1,2\n').candidates.map((c) => c.quoteChar))).toStrictEqual(
      new Set(['"']),
    );
    expect(
      detect("a,b\n1,it's\n").candidates.map((c) => [c.quoteChar, c.escapeChar]),
    ).toContainEqual(["'", "'"]);
    expect(detect("a,b\n1,it's \\ \n").candidates.every((c) => c.escapeChar === c.quoteChar)).toBe(
      true,
    );
  });
});

