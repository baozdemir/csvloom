describe('detect: bytes', () => {
  const bytes = (text: string) => new TextEncoder().encode(text);
  const DEFAULTS = {
    delimiter: ',',
    newline: '\n',
    quoteChar: '"',
    escapeChar: '"',
    header: false,
    start: 0,
    preamble: '',
    preambleLines: 0,
    sepLine: false,
    columns: 1,
    score: 0,
    candidates: [],
  };

  it('UTF-8 without a BOM', () => {
    expect(detect(bytes('é;b\n1;2\n'))).toMatchObject({
      delimiter: ';',
      start: 0,
      encoding: { name: 'utf-8', evidence: 'valid' },
    });
    expect(detect(new Uint8Array(0)).encoding).toStrictEqual({ name: 'utf-8', evidence: 'valid' });
  });

  it('UTF-8 with a BOM; start counts bytes', () => {
    const input = new Uint8Array([0xef, 0xbb, 0xbf, ...bytes('Özet\nid;x\n1;2\n')]);
    const found = detect(input);
    expect(found).toMatchObject({
      delimiter: ';',
      preamble: 'Özet\n',
      preambleLines: 1,
      // 3 bytes of BOM, then 'Özet\n' in 6 bytes.
      start: 9,
      encoding: { name: 'utf-8', evidence: 'bom' },
    });
    expect(new TextDecoder().decode(input.subarray(found.start))).toBe('id;x\n1;2\n');
    expect(detect(bytes('Özet\nid;x\n1;2\n')).start).toBe(6);
  });

  it.each([
    ['utf-16le', [0xff, 0xfe, 0x61, 0x00, 0x3b, 0x00]],
    ['utf-16be', [0xfe, 0xff, 0x00, 0x61, 0x00, 0x3b]],
  ])('%s by its BOM: reported, not decoded', (name, input) => {
    expect(detect(new Uint8Array(input))).toStrictEqual({
      ...DEFAULTS,
      encoding: { name, evidence: 'bom' },
      config: { delimiter: ',', newline: '\n', quoteChar: '"', escapeChar: '"', header: false },
    });
  });

  it('invalid UTF-8: the offset of the first bad byte', () => {
    expect(detect(new Uint8Array([0x61, 0xff, 0x62]))).toStrictEqual({
      ...DEFAULTS,
      encoding: { name: 'unknown', evidence: 'invalid', invalidAt: 1 },
      config: { delimiter: ',', newline: '\n', quoteChar: '"', escapeChar: '"', header: false },
    });
    const invalidAt = (input: number[]) => detect(new Uint8Array(input)).encoding?.invalidAt;
    // A lone continuation byte, an overlong form, a surrogate, a code point past U+10FFFF, and a
    // sequence the input's end cuts.
    expect(invalidAt([0x61, 0x62, 0x80])).toBe(2);
    expect(invalidAt([0xc0, 0xaf])).toBe(0);
    expect(invalidAt([0x61, 0xe0, 0x80, 0x80])).toBe(1);
    expect(invalidAt([0xed, 0xa0, 0x80])).toBe(0);
    expect(invalidAt([0xf4, 0x90, 0x80, 0x80])).toBe(0);
    expect(invalidAt([0x61, 0xe2, 0x82])).toBe(1);
    expect(invalidAt([0xf0, 0x9f, 0x98, 0x80])).toBeUndefined();
  });

  it('a 3-byte sequence cut at byte 262,144 is not reported as invalid', () => {
    const input = new Uint8Array(262_143 + 3).fill(0x61);
    input.set([0xe2, 0x82, 0xac], 262_143);
    expect(detect(input).encoding).toStrictEqual({ name: 'utf-8', evidence: 'valid' });
    // Only the first 262,144 bytes are checked.
    const late = new Uint8Array(262_144 + 2).fill(0x61);
    late[262_144] = 0xff;
    expect(detect(late).encoding).toStrictEqual({ name: 'utf-8', evidence: 'valid' });
    const inside = new Uint8Array(262_144).fill(0x61);
    inside[262_143] = 0xff;
    expect(detect(inside).encoding).toStrictEqual({
      name: 'unknown',
      evidence: 'invalid',
      invalidAt: 262_143,
    });
  });
});

