const GUARANTEE_BREAKS = ['\n', '\r\n', '\r'];
const GUARANTEE_LINES = [
  'Title',
  '',
  'Report 2026',
  'note "a, b" end',
  "it's",
  'x;y',
  'a,b',
  'p|q',
  '"open',
  'tab\there',
  '"closed, twice" and "again; here"',
  "'single, quoted'",
  '  ',
];

/** 2,000 seeded inputs: 0-25 random lines, then a generated table; some with a sep= line or a BOM. */
function guaranteeInputs() {
  const random = mulberry32(20261111);
  const pick = <T>(items: readonly T[]) => items[Math.floor(random() * items.length)] as T;
  const inputs: Array<{ input: string; sepLine: string; tableDelimiter: string }> = [];
  for (let i = 0; i < 2000; i++) {
    const tableDelimiter = pick([',', ';', '\t', '|']);
    let body = '';
    const lines = Math.floor(random() * 26);
    // Half of the inputs lead with free lines only, so that a preamble is common.
    const pool = random() < 0.5 ? GUARANTEE_LINES.slice(0, 5) : GUARANTEE_LINES;
    for (let n = 0; n < lines; n++) body += pick(pool) + pick(GUARANTEE_BREAKS);
    body += records(random, tableDelimiter, pick(GUARANTEE_BREAKS), pick(['"', "'"]));
    // Not "\r" alone: a body that starts with "\n" would complete it to one "\r\n".
    const sepLine = random() < 0.2 ? `sep=${tableDelimiter}${pick(['\n', '\r\n'])}` : '';
    const bom = random() < 0.2 ? '\ufeff' : '';
    inputs.push({ input: bom + sepLine + body, sepLine, tableDelimiter });
  }
  return inputs;
}

describe('the preamble guarantee', () => {
  /** Whether line (without its break) is free: no delimiter outside quote spans, and closed at its end. */
  function isFree(line: string, delimiters: readonly string[], quote: string): boolean {
    let quoted = false;
    for (let i = 0; i < line.length; i++) {
      if (line[i] === quote) quoted = !quoted;
      else if (!quoted && delimiters.some((d) => line.startsWith(d, i))) return false;
    }
    return !quoted;
  }

  it('holds for 2,000 seeded inputs', () => {
    let skipped = 0;
    let withSepLine = 0;
    for (const { input, sepLine, tableDelimiter } of guaranteeInputs()) {
      const found = detect(input);

      // What detection reads: the input after one leading U+FEFF (the body may start with one
      // too) and after the sep= line.
      const afterBom = input.startsWith('\ufeff') ? input.slice(1) : input;
      const read =
        sepLine !== '' && afterBom.startsWith(sepLine) ? afterBom.slice(sepLine.length) : afterBom;
      expect(found.sepLine, input).toBe(sepLine !== '' && afterBom.startsWith(sepLine));
      expect(found.preamble + input.slice(found.start), input).toBe(read);
      const physical = found.preamble.match(/[^\r\n]*(?:\r\n|\r|\n)/g) ?? [];
      expect(physical.join(''), input).toBe(found.preamble);
      expect(physical.length, input).toBe(found.preambleLines);
      expect(physical.length, input).toBeLessThanOrEqual(20);
      const effective = sepLine === '' ? DEFAULT_DELIMITERS : [tableDelimiter];
      for (const line of physical) {
        expect(isFree(line.replace(/[\r\n]+$/, ''), effective, found.quoteChar), input).toBe(true);
      }
      if (found.columns === 1) expect(found.preamble, input).toBe('');
      if (found.preamble !== '') skipped++;
      if (found.sepLine) withSepLine++;
    }
    // The property is not vacuous: many inputs have a preamble, and many a sep= line.
    expect(skipped).toBeGreaterThan(200);
    expect(withSepLine).toBeGreaterThan(200);
  });
});

describe('linear patterns', () => {
  it('are exactly these patterns', () => {
    expect(NUMBER_CELL.source).toBe(
      String.raw`^[+-]?(?:\d{1,3}(?:[.,\u00a0 ]\d{3})+|\d+)(?:[.,]\d+)?(?:[eE][+-]?\d+)?%?$`,
    );
    expect(DATE_CELL.source).toBe(
      String.raw`^\d{1,4}[-/.]\d{1,2}[-/.]\d{1,4}(?:[T ]\d{1,2}:\d{2}(?::\d{2}(?:\.\d+)?)?(?:Z|[+-]\d{2}:?\d{2})?)?$`,
    );
    expect(TIME_CELL.source).toBe(String.raw`^\d{1,2}:\d{2}(?::\d{2})?$`);
    for (const pattern of [NUMBER_CELL, DATE_CELL, TIME_CELL]) expect(pattern.flags).toBe('');
  });

  it('classify what they are meant to', () => {
    for (const cell of ['5', '-1,234.56', '1.234,56', '+5.2%', '-2e3', '1 234', '0,5']) {
      expect(NUMBER_CELL.test(cell), cell).toBe(true);
    }
    for (const cell of ['', 'x', '1,23,4', '1e', '5 %', '--1']) {
      expect(NUMBER_CELL.test(cell), cell).toBe(false);
    }
    for (const cell of ['2026-11-11', '11/11/2026', '11.11.26', '2026-11-11T09:30:00.5+03:00']) {
      expect(DATE_CELL.test(cell), cell).toBe(true);
    }
    expect(DATE_CELL.test('2026-11')).toBe(false);
    expect(TIME_CELL.test('9:30')).toBe(true);
    expect(TIME_CELL.test('09:30:15')).toBe(true);
    expect(TIME_CELL.test('9:3')).toBe(false);
  });

  // GUARD, not a measurement: the best of five runs on a shared machine, against a bound that a
  // quadratic pattern misses by orders of magnitude.
  const MIB = 1_048_576;
  const hostile: [string, string][] = [
    ['1 MiB of digits followed by x', '7'.repeat(MIB) + 'x'],
    ['1, + 300,000 × 234, + x', `1,${'234,'.repeat(300_000)}x`],
    ['1 MiB of 1-', '1-'.repeat(MIB / 2)],
  ];
  it.each(hostile)('reject a hostile cell in under 50 ms: %s', (_, cell) => {
    for (const pattern of [NUMBER_CELL, DATE_CELL, TIME_CELL]) {
      let best = Infinity;
      for (let run = 0; run < 5; run++) {
        const from = performance.now();
        const matched = pattern.test(cell);
        best = Math.min(best, performance.now() - from);
        expect(matched).toBe(false);
      }
      expect(best, pattern.source).toBeLessThan(50);
    }
  });

  it('does not test a cell longer than 64 units against them', () => {
    // A grouped number that holds the candidate ',': a value at 64 units, not clean at 65.
    const at64 = `+123${',456'.repeat(15)}`;
    const at65 = `1${',234'.repeat(16)}`;
    expect([at64.length, at65.length]).toStrictEqual([64, 65]);
    expect(NUMBER_CELL.test(at64) && NUMBER_CELL.test(at65)).toBe(true);
    const scoreOf = (cell: string) =>
      detect(`x;y\n${cell};1\n`).candidates.find((c) => c.delimiter === ';')?.score;
    // P = 1/2 under ';'; T is 4/4 with the 64-unit cell and 3/4 with the 65-unit one.
    expect(scoreOf(at64)).toBe(0.5);
    expect(scoreOf(at65)).toBe(0.375);
    // A 65-unit cell of digits is clean by the other rule, whatever the patterns say.
    expect(scoreOf('7'.repeat(65))).toBe(0.5);
  });
});

