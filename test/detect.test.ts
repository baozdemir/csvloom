type Named = Pick<
  Detection,
  | 'delimiter'
  | 'newline'
  | 'quoteChar'
  | 'escapeChar'
  | 'header'
  | 'start'
  | 'preamble'
  | 'preambleLines'
  | 'sepLine'
  | 'columns'
>;
const BASE: Named = {
  delimiter: ',',
  newline: '\n',
  quoteChar: '"',
  escapeChar: '"',
  header: true,
  start: 0,
  preamble: '',
  preambleLines: 0,
  sepLine: false,
  columns: 2,
};

/** The ten named keys, that candidates[0] is the winner, and what config holds. */
function expectDetection(found: Detection, expected: Named) {
  expect(found).toMatchObject(expected);
  const { delimiter, newline, quoteChar, escapeChar, header } = expected;
  expect(found.candidates[0]).toStrictEqual({
    delimiter,
    quoteChar,
    escapeChar,
    score: found.score,
  });
  expect(found.config).toStrictEqual({ delimiter, newline, quoteChar, escapeChar, header });
  expect(found.candidates.length).toBeLessThanOrEqual(5);
}

/** The rows a plain parse of the table gives with the detected dialect. */
const rowsOf = (input: string, found: Detection) =>
  parse(input.slice(found.start), { ...found.config, header: false }).data;

/** A result without meta.detected and meta.sepLine, the two keys a plain parse does not have. */
function withoutDetection<R extends { meta: FeatureResult<unknown>['meta'] }>(result: R) {
  const meta = { ...result.meta };
  delete meta.detected;
  delete meta.sepLine;
  return { ...result, meta };
}

/**
 * parseDetailed(input, { ...config, detect: true }) parses the table found starts: meta.detected
 * is found, and the rest is parse of input.slice(found.start) with the detected dialect, header
 * as config gives it. A U+FEFF is put in front of the table for parse to remove, so that one the
 * table itself starts with stays data, as in parseDetailed, which removes only the input's.
 */
function expectTableParse(input: string, config: DetailedConfig = {}, found = detect(input)) {
  const result = parseDetailed(input, { ...config, detect: true } as DetailedConfig);
  expect(result.meta.detected, input).toStrictEqual(found);
  expect(Object.hasOwn(result.meta, 'sepLine'), input).toBe(found.sepLine);
  const table = parse(`\ufeff${input.slice(found.start)}`, {
    ...config,
    ...found.config,
    header: config.header ?? false,
  } as ParseConfig);
  expect(withoutDetection(result), input).toStrictEqual(table);
  return result;
}

